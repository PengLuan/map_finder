def seed():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()

    try:
        # 导入省份
        for code, name, lng, lat in PROVINCES:
            if not db.query(Region).filter(Region.code == code).first():
                db.add(Region(code=code, name=name, level=1, lng=lng, lat=lat))
        print(f"省份数据: {len(PROVINCES)} 条")

        # 导入城市
        for code, name, parent, lng, lat in CITIES:
            if not db.query(Region).filter(Region.code == code).first():
                db.add(Region(code=code, name=name, level=2, parent_code=parent, lng=lng, lat=lat))
        print(f"城市数据: {len(CITIES)} 条")

        # 导入 POI
        for name, cat, lng, lat, adcode, diff, hint in POIS:
            exists = db.query(POI).filter(POI.name == name, POI.lng == lng).first()
            if not exists:
                db.add(POI(
                    name=name, category=cat, lng=lng, lat=lat,
                    adcode=adcode, difficulty=diff, hint_text=hint,
                ))
        print(f"POI 数据: {len(POIS)} 条")

        db.commit()

        # 为所有 POI 设置 OSS 封面地址（按 POI ID 对应 covers/{id}.jpg）
        all_pois = db.query(POI).all()
        for poi in all_pois:
            expected_url = f"{OSS_COVER_PREFIX}/{poi.id}.jpg"
            if poi.cover_url != expected_url:
                poi.cover_url = expected_url
        db.commit()
        print(f"封面地址: 已为 {len(all_pois)} 个 POI 设置 OSS 封面")

        print("种子数据导入完成!")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
